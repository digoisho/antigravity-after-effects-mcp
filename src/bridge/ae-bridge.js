import fs from "fs";
import path from "path";
import os from "os";
import { spawn, execSync } from "child_process";
import { JSX_RUNTIME_HELPERS } from "./jsx-helpers.js";

const BRIDGE_DIR = path.join(os.homedir(), ".ae-antigravity-bridge");

if (!fs.existsSync(BRIDGE_DIR)) {
  fs.mkdirSync(BRIDGE_DIR, { recursive: true });
}

let cachedAfterFxPath = null;

/**
 * Locate AfterFX.exe on Windows across running processes, Registry, and common install drives.
 */
export function findAfterEffectsExecutable() {
  if (process.env.AFTERFX_PATH && fs.existsSync(process.env.AFTERFX_PATH)) {
    return process.env.AFTERFX_PATH;
  }
  if (cachedAfterFxPath && fs.existsSync(cachedAfterFxPath)) {
    return cachedAfterFxPath;
  }

  // 1. Check known path on this machine first for instant lookup
  const knownCandidates = [
    "F:\\Softwares\\Adobe\\Adobe After Effects 2026\\Support Files\\AfterFX.exe",
    "C:\\Program Files\\Adobe\\Adobe After Effects 2026\\Support Files\\AfterFX.exe",
    "C:\\Program Files\\Adobe\\Adobe After Effects 2025\\Support Files\\AfterFX.exe",
    "C:\\Program Files\\Adobe\\Adobe After Effects 2024\\Support Files\\AfterFX.exe",
    "D:\\Program Files\\Adobe\\Adobe After Effects 2026\\Support Files\\AfterFX.exe"
  ];
  for (const candidate of knownCandidates) {
    if (fs.existsSync(candidate)) {
      cachedAfterFxPath = candidate;
      return candidate;
    }
  }

  // 2. Check Windows Registry App Paths
  try {
    const regOut = execSync(
      'powershell -NoProfile -Command "(Get-ItemProperty \'HKLM:\\SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\App Paths\\AfterFX.exe\' -ErrorAction SilentlyContinue).\'(default)\'"',
      { encoding: "utf8", timeout: 3000 }
    ).trim();
    if (regOut && fs.existsSync(regOut)) {
      cachedAfterFxPath = regOut;
      return regOut;
    }
  } catch (e) {}

  // 3. Check running AfterFX process
  try {
    const procOut = execSync(
      'powershell -NoProfile -Command "(Get-Process AfterFX -ErrorAction SilentlyContinue | Select-Object -First 1).Path"',
      { encoding: "utf8", timeout: 3000 }
    ).trim();
    if (procOut && fs.existsSync(procOut)) {
      cachedAfterFxPath = procOut;
      return procOut;
    }
  } catch (e) {}

  return null;
}

/**
 * Check if AfterFX.exe is currently running and whether Scripting File/Network Security is enabled.
 */
export function getAfterEffectsStatus() {
  const exePath = findAfterEffectsExecutable();
  let isRunning = false;
  try {
    const out = execSync(
      'powershell -NoProfile -Command "if (Get-Process AfterFX -ErrorAction SilentlyContinue) { \'RUNNING\' } else { \'STOPPED\' }"',
      { encoding: "utf8", timeout: 2500 }
    ).trim();
    isRunning = out.includes("RUNNING");
  } catch (e) {}

  let fileWriteEnabled = null;
  let prefsPathFound = null;
  try {
    const roamBase = path.join(os.homedir(), "AppData", "Roaming", "Adobe", "After Effects");
    if (fs.existsSync(roamBase)) {
      const versions = fs.readdirSync(roamBase).filter((d) => /^\d+\.\d+$/.test(d)).sort().reverse();
      for (const ver of versions) {
        const prefFile = path.join(roamBase, ver, `Adobe After Effects ${ver} Prefs.txt`);
        if (fs.existsSync(prefFile)) {
          prefsPathFound = prefFile;
          const content = fs.readFileSync(prefFile, "utf8");
          const match = content.match(/"Pref_SCRIPTING_FILE_NETWORK_SECURITY"\s*=\s*"?(\d+)"?/);
          if (match) {
            fileWriteEnabled = match[1] === "1";
          }
          break;
        }
      }
    }
  } catch (e) {}

  // Check if ScriptUI panel heartbeat is fresh
  let panelActive = false;
  const heartbeatFile = path.join(BRIDGE_DIR, "heartbeat.json");
  if (fs.existsSync(heartbeatFile)) {
    try {
      const stat = fs.statSync(heartbeatFile);
      panelActive = Date.now() - stat.mtimeMs < 5000;
    } catch (e) {}
  }

  return {
    executablePath: exePath,
    isRunning,
    panelActive,
    fileWriteEnabledInPrefsDisk: fileWriteEnabled,
    prefsFile: prefsPathFound,
    bridgeDir: BRIDGE_DIR
  };
}

/**
 * Builds the wrapped ES3 ExtendScript (.jsx) file that executes `scriptBody` inside an Undo Group
 * and writes the JSON result to `responseFilePath` if file writing is permitted.
 */
function buildWrappedExtendScript(scriptBody, undoGroupName, responseFilePath) {
  const escapedResPath = responseFilePath.replace(/\\/g, "/");
  const safeUndo = (undoGroupName || "Antigravity MCP Action").replace(/"/g, '\\"');

  return `// Auto-generated by Antigravity After Effects MCP Bridge
#target aftereffects
(function() {
${JSX_RUNTIME_HELPERS}

  var __resultPayload = { ok: true, data: null, error: null, timestamp: new Date().getTime() };
  var __undoStarted = false;

  try {
    app.beginSuppressDialogs();
  } catch (e) {}

  try {
    app.beginUndoGroup("${safeUndo}");
    __undoStarted = true;

    var __userFn = function() {
${scriptBody}
    };

    var __ret = __userFn();
    __resultPayload.data = (typeof __ret !== "undefined") ? __ret : { status: "executed" };
  } catch (__err) {
    __resultPayload.ok = false;
    __resultPayload.error = {
      message: String(__err.message || __err),
      line: __err.line || null,
      fileName: __err.fileName || null
    };
  } finally {
    if (__undoStarted) {
      try { app.endUndoGroup(); } catch (e) {}
    }
    try { app.endSuppressDialogs(false); } catch (e) {}
  }

  // Write response JSON back to bridge directory if allowed
  try {
    var secPref = 1;
    try {
      secPref = app.preferences.getPrefAsLong("Main Pref Section v2", "Pref_SCRIPTING_FILE_NETWORK_SECURITY");
    } catch (ePref) {}

    if (secPref === 1) {
      var outFile = new File("${escapedResPath}");
      outFile.encoding = "UTF-8";
      if (outFile.open("w")) {
        outFile.write(aeJsonStringify(__resultPayload));
        outFile.close();
      }
    }
  } catch (__writeErr) {}
})();
`;
}

/**
 * Execute ExtendScript in After Effects using either:
 * 1. Active ScriptUI Panel queue (if AE-Antigravity-Bridge panel is open and polling)
 * 2. Direct `AfterFX.exe -r <script.jsx>` IPC injection into the running After Effects instance
 */
export async function executeInAfterEffects(scriptBody, options = {}) {
  const {
    undoName = "Antigravity MCP Action",
    timeoutMs = 15000
  } = options;

  const reqId = `${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;
  const cmdFile = path.join(BRIDGE_DIR, `cmd_${reqId}.jsx`);
  const resFile = path.join(BRIDGE_DIR, `res_${reqId}.json`);
  const queueFile = path.join(BRIDGE_DIR, "next_command.jsx");

  const wrappedJsx = buildWrappedExtendScript(scriptBody, undoName, resFile);
  fs.writeFileSync(cmdFile, wrappedJsx, "utf8");

  const status = getAfterEffectsStatus();

  // If the dockable ScriptUI panel is actively polling, drop into queue file as well
  if (status.panelActive) {
    try {
      fs.writeFileSync(queueFile, wrappedJsx, "utf8");
    } catch (e) {}
  }

  // Also dispatch via AfterFX.exe -r if panel isn't active (or as immediate trigger)
  if (!status.panelActive) {
    if (!status.executablePath) {
      throw new Error(
        "Could not locate AfterFX.exe. Please set AFTERFX_PATH environment variable or ensure Adobe After Effects is installed."
      );
    }
    await new Promise((resolve) => {
      try {
        const child = spawn(status.executablePath, ["-r", cmdFile], {
          detached: false,
          stdio: "ignore",
          windowsHide: false
        });
        const spawnTimer = setTimeout(() => {
          resolve();
        }, 3500);
        child.on("close", () => {
          clearTimeout(spawnTimer);
          resolve();
        });
        child.on("error", () => {
          clearTimeout(spawnTimer);
          resolve();
        });
      } catch (e) {
        resolve();
      }
    });
  }

  // Poll for response file `res_<reqId>.json`
  const waitBudget = status.fileWriteEnabledInPrefsDisk === false ? 1500 : timeoutMs;
  const startWait = Date.now();
  let responseData = null;

  while (Date.now() - startWait < waitBudget) {
    if (fs.existsSync(resFile)) {
      try {
        const raw = fs.readFileSync(resFile, "utf8").trim();
        if (raw.length > 0) {
          responseData = JSON.parse(raw);
          break;
        }
      } catch (e) {
        // File might still be flushing
      }
    }
    await new Promise((r) => setTimeout(r, 120));
  }

  // Cleanup temporary files
  try {
    if (fs.existsSync(cmdFile)) fs.unlinkSync(cmdFile);
    if (fs.existsSync(resFile)) fs.unlinkSync(resFile);
  } catch (e) {}

  if (responseData) {
    if (!responseData.ok) {
      throw new Error(
        `After Effects ExtendScript Error: ${responseData.error?.message || "Unknown error"} (Line: ${responseData.error?.line || "N/A"})`
      );
    }
    return {
      executed: true,
      readbackAvailable: true,
      result: responseData.data
    };
  }

  // If no response file was written, the script still executed via AfterFX.exe -r,
  // but file write security preference may be disabled in After Effects.
  return {
    executed: true,
    readbackAvailable: false,
    result: {
      status: "dispatched_to_after_effects",
      note:
        "The ExtendScript command was sent and executed in After Effects via AfterFX.exe -r. " +
        "To enable two-way JSON readback (inspecting layers/rendering frames), enable in After Effects: " +
        "Edit > Preferences > Scripting & Expressions > 'Allow Scripts to Write Files and Access Network'."
    }
  };
}

